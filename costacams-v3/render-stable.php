    $channelAnchor='<section class="section" id="channels">';
    if(str_contains($html,$channelAnchor))$html=str_replace($channelAnchor,$surfHome.$channelAnchor,$html);

    // Put the decision tool in the main navigation between Map and Cameras.
    $html=str_replace('<a href="/map">Map</a><a href="/#channels">Channels</a>','<a href="/map">Map</a><a href="/#surf-match">Find a surf</a><a href="/#channels">Channels</a>',$html);

    $switchJs=<<<HTML
<script id="cc-rec-stable-switcher">
(function(){
  const cams={$recJson};
  window.__ccRecommendedLocked=true;
  if(!cams.length){
    const b=document.getElementById('ccRecPreview');if(b)b.innerHTML='<div class="cc-rec-preview-error">No recommended live preview is available right now.</div>';
    const n=document.getElementById('ccRecName');if(n)n.textContent='Browse live cameras';
    return;
  }
  let idx=0,currentHls=null,hlsLoading=false,hlsQueue=[];
  try{const last=sessionStorage.getItem('ccLastRecommended')||'';const choices=cams.map((c,i)=>i).filter(i=>cams[i].slug!==last);const pool=choices.length?choices:cams.map((c,i)=>i);idx=pool[Math.floor(Math.random()*pool.length)];}catch(e){idx=Math.floor(Math.random()*cams.length);}
  function ensureHls(done){
    if(window.Hls){done();return;}hlsQueue.push(done);if(hlsLoading)return;hlsLoading=true;
    const s=document.createElement('script');s.src='https://cdn.jsdelivr.net/npm/hls.js@latest';s.async=true;s.onload=()=>{hlsLoading=false;const q=hlsQueue.splice(0);q.forEach(fn=>fn());};s.onerror=()=>{hlsLoading=false;hlsQueue.length=0;};document.head.appendChild(s);
  }
  function buttons(){
    const list=document.getElementById('ccRecList');if(!list)return;list.innerHTML='';
    cams.forEach((c,i)=>{const b=document.createElement('button');b.type='button';b.className='cc-rec-choice'+(i===idx?' active':'');b.textContent=c.name;b.addEventListener('click',()=>show(i,'list'));list.appendChild(b);});
  }
  function show(i,method){
    idx=(i+cams.length)%cams.length;const c=cams[idx];
    try{sessionStorage.setItem('ccLastRecommended',c.slug);}catch(e){}
    if(currentHls){try{currentHls.destroy();}catch(e){}currentHls=null;}
    const box=document.getElementById('ccRecPreview'),name=document.getElementById('ccRecName'),region=document.getElementById('ccRecRegion'),link=document.getElementById('ccRecLink');
    if(name)name.textContent=c.name;if(region)region.textContent=c.region;if(link){link.href='/'+encodeURIComponent(c.slug);link.textContent='Open '+c.name+' →';}
    buttons();if(!box)return;box.innerHTML='';
    const v=document.createElement('video');v.muted=true;v.autoplay=true;v.playsInline=true;v.controls=true;v.preload='metadata';box.appendChild(v);
    const fail=()=>{if(box.contains(v))box.innerHTML='<div class="cc-rec-preview-error">Preview did not start. Choose another camera below.</div>';};
    if(v.canPlayType('application/vnd.apple.mpegurl')){v.src=c.url;v.play().catch(()=>{});v.addEventListener('error',fail,{once:true});}
    else ensureHls(()=>{if(window.Hls&&Hls.isSupported()){currentHls=new Hls({enableWorker:true,maxBufferLength:10});currentHls.loadSource(c.url);currentHls.attachMedia(v);currentHls.on(Hls.Events.MANIFEST_PARSED,()=>v.play().catch(()=>{}));currentHls.on(Hls.Events.ERROR,(e,d)=>{if(d&&d.fatal)fail();});}else fail();});
    if(method&&window.gtag)gtag('event','recommended_camera_select',{camera_slug:c.slug,selection_method:method});
  }
  const next=document.getElementById('ccRecNext');if(next)next.addEventListener('click',()=>show(idx+1,'next'));
  show(idx,'initial');
})();
</script>
HTML;
