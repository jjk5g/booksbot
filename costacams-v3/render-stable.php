    $html=str_replace('</head>',$surfCss.'</head>',$html);

    $surfHome=<<<'HTML'
<section class="section cc-home-surf-match" id="surf-match">
  <div class="cc-home-surf-card">
    <div class="cc-home-surf-copy">
      <span class="tag">SURF MATCH · BETA</span>
