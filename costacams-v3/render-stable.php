    $recJson=json_encode($recCams,JSON_UNESCAPED_SLASHES|JSON_UNESCAPED_UNICODE|JSON_HEX_TAG|JSON_HEX_AMP|JSON_HEX_APOS|JSON_HEX_QUOT)?:'[]';

    $controls='<div class="cc-rec-switcher"><button type="button" class="cc-rec-next" id="ccRecNext">Next camera →</button><div class="cc-rec-list" id="ccRecList" aria-label="Recommended live cameras"></div></div>';
    $html=str_replace('<a class="cc-map-btn" id="ccRecLink" href="/#channels">Browse cameras →</a></div></aside>','<a class="cc-map-btn" id="ccRecLink" href="/#channels">Browse cameras →</a>'.$controls.'</div></aside>',$html);

    $css=<<<'HTML'
