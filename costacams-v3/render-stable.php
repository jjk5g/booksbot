<?php
declare(strict_types=1);

$slug=preg_replace('/[^a-z0-9-]/','',strtolower((string)($_GET['slug']??'')));
ob_start();
require __DIR__.'/render-fast.php';
$html=ob_get_clean();

if($slug===''){
    // Remove the old automatic failover rotator. It could repeatedly switch
    // cameras when a stream was slow to start even though the page itself was fine.
    $html=preg_replace('~<script id="cc-recommended-fallback">.*?</script>~s','',$html)??$html;

    // Prevent the older renderer from selecting/changing another camera. The
    // switcher below owns the recommendation preview for the whole page load.
    $html=str_replace(
        'function renderRecommended(){',
        'function renderRecommended(){if(window.__ccRecommendedLocked)return;window.__ccRecommendedLocked=true;',
        $html
    );
    $html=str_replace(
        'Rotates through selected high-quality live coastal cameras.',
        'Choose another recommended live camera below without leaving this page.',
        $html
    );
    $html=str_replace(
        'Selected once from high-quality live coastal cameras.',
        'Choose another recommended live camera below without leaving this page.',
        $html
    );

    // Read the curated HLS-only recommendation pool already generated by
    // render-fast.php. This deliberately excludes low-quality iframe feeds.
    $recCams=[];
    if(preg_match('~const candidates=(\[[^;]*\]);~s',$html,$m)){
        $decoded=json_decode($m[1],true);
        if(is_array($decoded))$recCams=array_values(array_filter($decoded,fn($r)=>is_array($r)&&!empty($r['slug'])&&!empty($r['url'])));
    }
    $recJson=json_encode($recCams,JSON_UNESCAPED_SLASHES|JSON_UNESCAPED_UNICODE|JSON_HEX_TAG|JSON_HEX_AMP|JSON_HEX_APOS|JSON_HEX_QUOT)?:'[]';

    $controls='<div class="cc-rec-switcher"><button type="button" class="cc-rec-next" id="ccRecNext">Next camera →</button><div class="cc-rec-list" id="ccRecList" aria-label="Recommended live cameras"></div></div>';
    $html=str_replace('<a class="cc-map-btn" id="ccRecLink" href="/#channels">Browse cameras →</a></div></aside>','<a class="cc-map-btn" id="ccRecLink" href="/#channels">Browse cameras →</a>'.$controls.'</div></aside>',$html);

    $css=<<<'HTML'
<style id="cc-rec-switcher-style">
.cc-rec-switcher{margin-top:14px;padding-top:12px;border-top:1px solid #242c2f}.cc-rec-next{width:100%;border:1px solid #3b6670;background:#0b1b20;color:#d6f7ff;border-radius:10px;padding:9px 11px;font-weight:800;cursor:pointer}.cc-rec-next:hover{background:#102a31}.cc-rec-list{display:flex;gap:6px;overflow-x:auto;padding:9px 1px 2px;scrollbar-width:thin}.cc-rec-choice{flex:0 0 auto;border:1px solid #2c3538;background:#101416;color:#aeb9bd;border-radius:999px;padding:5px 8px;font-size:10px;cursor:pointer;white-space:nowrap}.cc-rec-choice.active{border-color:#50dcff;color:#c9f6ff;background:#0d2025}.cc-rec-preview-error{color:#98a6ab;text-align:center;padding:18px;font-size:12px}
</style>
HTML;
    $html=str_replace('</head>',$css.'</head>',$html);

    $switchJs=<<<HTML
<script id="cc-rec-stable-switcher">
(function(){
  const cams={$recJson};
  window.__ccRecommendedLocked=true;
  if(!cams.length){
    const b=document.getElementById('ccRecPreview');if(b)b.innerHTML='<div class="cc-rec-preview-error">No recommended live preview is available right now.</div>';
    const n=document.getElementById('ccRecName');if(n)n.textContent='Browse live cameras';
    return;
  }
  let idx=0,currentHls=null,hlsLoading=false,hlsQueue=[];
  try{const last=sessionStorage.getItem('ccLastRecommended')||'';const choices=cams.map((c,i)=>i).filter(i=>cams[i].slug!==last);const pool=choices.length?choices:cams.map((c,i)=>i);idx=pool[Math.floor(Math.random()*pool.length)];}catch(e){idx=Math.floor(Math.random()*cams.length);}
  function ensureHls(done){
    if(window.Hls){done();return;}hlsQueue.push(done);if(hlsLoading)return;hlsLoading=true;
    const s=document.createElement('script');s.src='https://cdn.jsdelivr.net/npm/hls.js@latest';s.async=true;s.onload=()=>{hlsLoading=false;const q=hlsQueue.splice(0);q.forEach(fn=>fn());};s.onerror=()=>{hlsLoading=false;hlsQueue.length=0;};document.head.appendChild(s);
  }
  function buttons(){
    const list=document.getElementById('ccRecList');if(!list)return;list.innerHTML='';
    cams.forEach((c,i)=>{const b=document.createElement('button');b.type='button';b.className='cc-rec-choice'+(i===idx?' active':'');b.textContent=c.name;b.addEventListener('click',()=>show(i,'list'));list.appendChild(b);});
  }
  function show(i,method){
    idx=(i+cams.length)%cams.length;const c=cams[idx];
    try{sessionStorage.setItem('ccLastRecommended',c.slug);}catch(e){}
    if(currentHls){try{currentHls.destroy();}catch(e){}currentHls=null;}
    const box=document.getElementById('ccRecPreview'),name=document.getElementById('ccRecName'),region=document.getElementById('ccRecRegion'),link=document.getElementById('ccRecLink');
    if(name)name.textContent=c.name;if(region)region.textContent=c.region;if(link){link.href='/'+encodeURIComponent(c.slug);link.textContent='Open '+c.name+' →';}
    buttons();if(!box)return;box.innerHTML='';
    const v=document.createElement('video');v.muted=true;v.autoplay=true;v.playsInline=true;v.controls=true;v.preload='metadata';box.appendChild(v);
    const fail=()=>{if(box.contains(v))box.innerHTML='<div class="cc-rec-preview-error">Preview did not start. Choose another camera below.</div>';};
    if(v.canPlayType('application/vnd.apple.mpegurl')){v.src=c.url;v.play().catch(()=>{});v.addEventListener('error',fail,{once:true});}
    else ensureHls(()=>{if(window.Hls&&Hls.isSupported()){currentHls=new Hls({enableWorker:true,maxBufferLength:10});currentHls.loadSource(c.url);currentHls.attachMedia(v);currentHls.on(Hls.Events.MANIFEST_PARSED,()=>v.play().catch(()=>{}));currentHls.on(Hls.Events.ERROR,(e,d)=>{if(d&&d.fatal)fail();});}else fail();});
    if(method&&window.gtag)gtag('event','recommended_camera_select',{camera_slug:c.slug,selection_method:method});
  }
  const next=document.getElementById('ccRecNext');if(next)next.addEventListener('click',()=>show(idx+1,'next'));
  show(idx,'initial');
})();
</script>
HTML;
    $html=str_replace('</body>',$switchJs.'</body>',$html);

    // Keep first paint light. The embedded map starts after the page itself is visible.
    $html=str_replace("requestIdleCallback(loadMap,{timeout:650})","requestIdleCallback(loadMap,{timeout:1600})",$html);
    $html=str_replace('else setTimeout(loadMap,160);','else setTimeout(loadMap,1000);',$html);
}

echo $html;
