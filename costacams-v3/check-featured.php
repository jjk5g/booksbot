$out=[];
foreach($streams as $slug=>$stream){
 $url=$base.$stream.'/playlist.m3u8';
 $ch=curl_init($url);
 curl_setopt_array($ch,[CURLOPT_RETURNTRANSFER=>true,CURLOPT_FOLLOWLOCATION=>true,CURLOPT_CONNECTTIMEOUT=>4,CURLOPT_TIMEOUT=>8,CURLOPT_USERAGENT=>'CostaCamsHealth/1.0']);
